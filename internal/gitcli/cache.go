package gitcli

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// GlobalConfigPath is the generated global config inside the cache root.
func GlobalConfigPath(base string) string { return filepath.Join(base, "gitconfig") }

// CacheDir is an approved URL's cache: <base>/<sha256 of the URL>.git.
func CacheDir(base, approvedURL string) string {
	sum := sha256.Sum256([]byte(approvedURL))
	return filepath.Join(base, hex.EncodeToString(sum[:])+".git")
}

// EnsureBase creates the cache root, owner-only.
func EnsureBase(base string) error {
	if err := os.MkdirAll(base, 0o700); err != nil {
		return err
	}
	return os.Chmod(base, 0o700)
}

// WriteGlobalConfig writes the generated global config (slice 6 note §3.2):
// the owner's credential helpers in order and BatchMode ssh - nothing else.
// caInfo trusts one extra CA bundle and is set only by tests (§8: the
// HTTPS http-backend fixture); production passes "".
func WriteGlobalConfig(path string, h Helpers, caInfo string) error {
	var b strings.Builder
	b.WriteString("# Generated by Klyx at startup; every edit is overwritten.\n")
	if len(h.Values) > 0 {
		b.WriteString("[credential]\n")
		for _, v := range h.Values {
			fmt.Fprintf(&b, "\thelper = %s\n", quoteConfig(v))
		}
	}
	b.WriteString("[core]\n\tsshCommand = " + quoteConfig("ssh -o BatchMode=yes") + "\n")
	if caInfo != "" {
		b.WriteString("[http]\n\tsslCAInfo = " + quoteConfig(caInfo) + "\n")
	}
	return WriteFileDurable(path, []byte(b.String()), 0o600)
}

// writeRepoConfig replaces a repository's config with the partial-clone
// config of parent §7: format version 1, origin the approved URL as a
// promisor with blob:none. No fetch refspec: every fetch names its own.
func writeRepoConfig(gitDir, approvedURL string) error {
	cfg := "[core]\n" +
		"\trepositoryformatversion = 1\n" +
		"\tbare = true\n" +
		"\tlogAllRefUpdates = false\n" +
		"[gc]\n" +
		"\tauto = 0\n" +
		"[extensions]\n" +
		"\tpartialClone = origin\n" +
		"[remote \"origin\"]\n" +
		"\turl = " + quoteConfig(approvedURL) + "\n" +
		"\tpromisor = true\n" +
		"\tpartialclonefilter = blob:none\n"
	return WriteFileDurable(filepath.Join(gitDir, "config"), []byte(cfg), 0o600)
}

// InitRepo creates a bare partial-clone repository at gitDir - a cache or a
// staging repo - for an approved URL. gitDir must not exist yet.
func (r Runner) InitRepo(ctx context.Context, gitDir, approvedURL string) error {
	if err := ValidateApprovedURL(approvedURL); err != nil {
		return err
	}
	if err := os.Mkdir(gitDir, 0o700); err != nil {
		if errors.Is(err, os.ErrExist) {
			return fmt.Errorf("%s already exists", gitDir)
		}
		return err
	}
	c, err := initBare(gitDir)
	if err == nil {
		_, err = r.run(ctx, c)
	}
	if err == nil {
		err = writeRepoConfig(gitDir, approvedURL)
	}
	if err == nil {
		err = SyncDir(filepath.Dir(gitDir))
	}
	if err != nil {
		_ = os.RemoveAll(gitDir)
		return err
	}
	return nil
}

// quoteConfig writes a git config value as a quoted string.
func quoteConfig(v string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\t", `\t`, "\b", `\b`)
	return `"` + r.Replace(v) + `"`
}

// WriteFileDurable writes a file durably: a temporary file in the same
// directory, fsynced, renamed over the target, then the directory fsynced.
func WriteFileDurable(path string, data []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer func() { _ = os.Remove(tmp) }()
	if err := f.Chmod(perm); err != nil {
		_ = f.Close()
		return err
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}
	return SyncDir(dir)
}

// SyncDir fsyncs a directory, making a rename or removal in it durable.
func SyncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer func() { _ = d.Close() }()
	return d.Sync()
}
